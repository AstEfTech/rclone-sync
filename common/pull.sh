#!/usr/bin/env bash
# One-way transfer remote -> local disk for each configured folder pair, with the rclone
# command chosen per pair: copy (default, deletes nothing), sync (mirror, deletes extra
# files at the destination), move (deletes source files after transfer) or twoway
# (copy in both directions, deletes nothing).
# Installed by deploy.sh as <NAME>-pull.sh next to provider.conf and a generated .env.
# Run as run_user, not via sudo.
# Debug: LOG_LEVEL=DEBUG ./<NAME>-pull.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"

# Provider-specific rclone options (RCLONE_ARGS, RECONNECT_ON_ERROR)
# shellcheck source=/dev/null
. "$SCRIPT_DIR/provider.conf"

# Settings for this provider (the PAIR_* arrays, MOUNT_POINT) are generated by deploy.sh
# from config.yml and live next to the script. PAIR_NAMES/PAIR_SRC/PAIR_DST/PAIR_MODE are
# parallel arrays: one element per folder pair, mode = copy | sync | move
# shellcheck source=/dev/null
if [ ! -f "$SCRIPT_DIR/.env" ]; then
  echo "Missing $SCRIPT_DIR/.env: run the installed copy (see deploy.sh)" >&2
  exit 1
fi
. "$SCRIPT_DIR/.env"
[ "${#PAIR_NAMES[@]}" -gt 0 ] || { echo "No folder pairs in .env: rerun deploy.sh" >&2; exit 1; }
MOUNT="${MOUNT_POINT:-}"   # optional: empty = no separate mounted disk

# Optional, from config.yml via .env; defaults when unset
MIN_FREE_GB="${MIN_FREE_GB:-5}"
KEEP_LOG_DAYS="${KEEP_LOG_DAYS:-14}"
LOG_LEVEL="${LOG_LEVEL:-INFO}"

LOG_DIR="$SCRIPT_DIR/log"
LOCK_FILE="$SCRIPT_DIR/.lock"

# --- Lock: shared by the timer and manual runs
exec 9>"$LOCK_FILE"
if ! flock -n 9; then
  echo "Previous run still in progress, skip"
  exit 0
fi

# --- Log: file name = run start time
LOG="$LOG_DIR/$(date +%Y-%m-%d_%H-%M-%S).log"
mkdir -p "$LOG_DIR"
find "$LOG_DIR" -name '*.log' -mtime +"$KEEP_LOG_DAYS" -delete

log() { echo "$(date '+%F %T') $*" | tee -a "$LOG" >&2; }

# --- Checks
if [ -n "$MOUNT" ] && ! mountpoint -q "$MOUNT"; then
  log "ERROR: $MOUNT is not mounted, skip"
  exit 1
fi

run_rclone() {
  rclone "$@" \
    "${RCLONE_ARGS[@]}" \
    --stats 30s --stats-file-name-length 0 \
    --log-file "$LOG" --log-level "$LOG_LEVEL"
}

# --- Pairs: one after another; a failed pair does not stop the others,
# the exit code is that of the last failure
rc=0
for i in "${!PAIR_NAMES[@]}"; do
  name="${PAIR_NAMES[$i]}" SRC="${PAIR_SRC[$i]}" DST="${PAIR_DST[$i]}" MODE="${PAIR_MODE[$i]}"

  # Free space of the mount, or of the nearest existing parent of DST (not created yet on first run)
  SPACE_PATH="${MOUNT:-$DST}"
  while [ ! -e "$SPACE_PATH" ]; do SPACE_PATH="$(dirname "$SPACE_PATH")"; done
  FREE_GB=$(df --output=avail -BG "$SPACE_PATH" | tail -1 | tr -dc '0-9')
  if [ "$FREE_GB" -lt "$MIN_FREE_GB" ]; then
    log "ERROR [$name]: only ${FREE_GB}G free on $SPACE_PATH, skip"
    rc=1
    continue
  fi

  log "START [$name] $MODE $SRC -> $DST"
  prc=0
  if [ "$MODE" = twoway ]; then
    # Both directions with copy (never deletes); --update keeps the newer file when both
    # sides have it, so an old copy never overwrites a fresher one
    run_rclone copy "$SRC" "$DST" --update || prc=$?
    [ "$prc" -ne 0 ] || run_rclone copy "$DST" "$SRC" --update || prc=$?
  else
    run_rclone "$MODE" "$SRC" "$DST" || prc=$?
  fi

  if [ "$prc" -ne 0 ]; then
    log "ERROR [$name]: rclone exited with code $prc"
    if [ "${RECONNECT_ON_ERROR:-0}" = 1 ]; then
      log "If it is an authentication error, run: rclone config reconnect ${SRC%%:*}:"
    fi
    rc=$prc
    continue
  fi
  log "DONE [$name]"
done
exit "$rc"
